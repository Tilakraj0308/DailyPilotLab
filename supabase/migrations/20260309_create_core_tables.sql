-- ==========================================================================
-- Core schema: extensions, enums, tables, indexes, triggers
-- ==========================================================================

-- Enable the pgvector extension if it hasn't been enabled yet
CREATE EXTENSION IF NOT EXISTS vector SCHEMA extensions;

-- -------------------------------------------------------------------------
-- Enum: trait_category
-- -------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'trait_category') THEN
        CREATE TYPE public.trait_category AS ENUM (
            'interest',
            'goal',
            'skill',
            'routine',
            'workstyle',
            'preference',
            'avoidance',
            'value',
            'constraint'
        );
    END IF;
END
$$;

-- -------------------------------------------------------------------------
-- raw_idea
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.raw_idea (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    content     TEXT NULL DEFAULT '',
    embeddings  extensions.vector(1536) NULL,
    raw         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT rawIdea_pkey PRIMARY KEY (id)
);

-- -------------------------------------------------------------------------
-- topic
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.topic (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP WITHOUT TIME ZONE NULL DEFAULT now(),
    title               TEXT NOT NULL,
    summary             TEXT NOT NULL,
    summary_embedding   extensions.vector(1536) NULL,
    activity_7d         SMALLINT NOT NULL DEFAULT 0,
    activity_30d        SMALLINT NOT NULL DEFAULT 0,
    lifetime_size       INTEGER NOT NULL DEFAULT 0,
    last_activity_at    TIME WITHOUT TIME ZONE NULL DEFAULT now(),
    is_archived         BOOLEAN NOT NULL DEFAULT FALSE,
    recency_strength    REAL NOT NULL DEFAULT 0,
    dominance           REAL NOT NULL DEFAULT 0,
    CONSTRAINT topic_pkey PRIMARY KEY (id)
);

-- Trigger: keep updated_at current on every UPDATE
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'update_topic_updated_at'
          AND tgrelid = 'public.topic'::regclass
    ) THEN
        CREATE TRIGGER update_topic_updated_at
        BEFORE UPDATE ON public.topic
        FOR EACH ROW
        EXECUTE FUNCTION storage.update_updated_at_column();
    END IF;
END
$$;

-- -------------------------------------------------------------------------
-- idea_topics (junction)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.idea_topics (
    idea_id     BIGINT NOT NULL,
    topic_id    BIGINT NOT NULL,
    CONSTRAINT idea_topics_pkey PRIMARY KEY (idea_id, topic_id),
    CONSTRAINT idea_topics_idea_id_fkey
        FOREIGN KEY (idea_id) REFERENCES public.raw_idea (id) ON DELETE CASCADE,
    CONSTRAINT idea_topics_topic_id_fkey
        FOREIGN KEY (topic_id) REFERENCES public.topic (id) ON DELETE CASCADE
);

-- -------------------------------------------------------------------------
-- trait
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.trait (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP WITH TIME ZONE NULL DEFAULT now(),
    trait_text  TEXT NOT NULL,
    trait_type  public.trait_category NOT NULL,
    confidence  REAL NOT NULL DEFAULT 0.1,
    embedding   extensions.vector(1536) NULL,
    CONSTRAINT trait_pkey PRIMARY KEY (id),
    CONSTRAINT trait_confidence_check CHECK (
        confidence >= 0.0 AND confidence <= 1.0
    )
);

-- HNSW index on trait embeddings for fast cosine-similarity lookups
CREATE INDEX IF NOT EXISTS idx_trait_embedding
    ON public.trait USING hnsw (embedding extensions.vector_cosine_ops);

