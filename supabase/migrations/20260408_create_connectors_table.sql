-- ==========================================================================
-- Connectors table: stores encrypted OAuth tokens for third-party services
-- ==========================================================================

CREATE TABLE IF NOT EXISTS public.connectors (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    provider                TEXT NOT NULL CHECK (provider IN ('google_calendar')),
    provider_account_id     TEXT,            -- Google 'sub' (stable unique ID)
    provider_account_email  TEXT,            -- Google email (for UI display)
    scopes                  TEXT[] NOT NULL DEFAULT '{}',
    access_token_enc        BYTEA,           -- AES-256-GCM encrypted
    refresh_token_enc       BYTEA,           -- AES-256-GCM encrypted
    token_nonce             BYTEA,           -- GCM nonce for this token pair
    expires_at              TIMESTAMPTZ,     -- access token expiry
    revoked_at              TIMESTAMPTZ,     -- soft-delete on disconnect/revoke
    connected_at            TIMESTAMPTZ,     -- when successfully connected
    last_sync_at            TIMESTAMPTZ,     -- last successful calendar fetch
    created_at              TIMESTAMPTZ DEFAULT now(),
    updated_at              TIMESTAMPTZ DEFAULT now(),
    CONSTRAINT uq_user_provider UNIQUE (user_id, provider)
);

-- Fast lookup by user
CREATE INDEX IF NOT EXISTS idx_connectors_user ON public.connectors(user_id);

-- Auto-update updated_at on every row modification
CREATE OR REPLACE FUNCTION public.trigger_set_connectors_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'set_connectors_updated_at'
          AND tgrelid = 'public.connectors'::regclass
    ) THEN
        CREATE TRIGGER set_connectors_updated_at
            BEFORE UPDATE ON public.connectors
            FOR EACH ROW
            EXECUTE FUNCTION public.trigger_set_connectors_timestamp();
    END IF;
END
$$;
