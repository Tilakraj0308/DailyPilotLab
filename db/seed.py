"""
Seed script for DailyPilotLab.

- Creates the `raw_idea`, `topic`, and `idea_topics` tables (with the pgvector
  extension enabled) in a Supabase Postgres instance whose credentials are read
  from the .env file (same keys as .env.example).
- Inserts a set of sample ideas so the app has something to work with from day one.

Usage:
    python -m db.seed
"""

import psycopg2
from dotenv import load_dotenv
import os

load_dotenv()

USER = os.getenv("user")
PASSWORD = os.getenv("password")
HOST = os.getenv("host")
PORT = os.getenv("port")
DBNAME = os.getenv("dbname")

# ---------------------------------------------------------------------------
# DDL – tables (idempotent: CREATE TABLE IF NOT EXISTS)
# ---------------------------------------------------------------------------

DDL = """
-- Enable the pgvector extension if it hasn't been enabled yet
CREATE EXTENSION IF NOT EXISTS vector SCHEMA extensions;

-- raw_idea -----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.raw_idea (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    content     TEXT NULL DEFAULT '',
    embeddings  extensions.vector NULL,
    raw         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT rawIdea_pkey PRIMARY KEY (id)
);

-- topic --------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.topic (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP WITHOUT TIME ZONE NULL DEFAULT now(),
    title               TEXT NOT NULL,
    summary             TEXT NOT NULL,
    summary_embedding   extensions.vector NULL,
    activity_7d         SMALLINT NOT NULL DEFAULT 0,
    activity_30d        SMALLINT NOT NULL DEFAULT 0,
    lifetime_size       INTEGER NOT NULL DEFAULT 0,
    last_activity_at    TIME WITHOUT TIME ZONE NULL DEFAULT now(),
    is_archived         BOOLEAN NOT NULL DEFAULT FALSE,
    recency_strength    REAL NOT NULL DEFAULT 0,
    dominance           REAL NOT NULL DEFAULT 0,
    CONSTRAINT topic_pkey PRIMARY KEY (id)
);

-- idea_topics (junction) ---------------------------------------------------
CREATE TABLE IF NOT EXISTS public.idea_topics (
    idea_id     BIGINT NOT NULL,
    topic_id    BIGINT NOT NULL,
    CONSTRAINT idea_topics_pkey PRIMARY KEY (idea_id, topic_id),
    CONSTRAINT idea_topics_idea_id_fkey
        FOREIGN KEY (idea_id) REFERENCES raw_idea (id) ON DELETE CASCADE,
    CONSTRAINT idea_topics_topic_id_fkey
        FOREIGN KEY (topic_id) REFERENCES topic (id) ON DELETE CASCADE
);
"""

# ---------------------------------------------------------------------------
# Seed data – ideas taken directly from ideas_inject.json
# ---------------------------------------------------------------------------

SEED_IDEAS = [
    "We don't actually see objects; we just see the light that failed to pass through them.",
    "Flibber-gasket the mimsy-wobble before the glorp transcends.",
    'The "oldest person on Earth" is a title that has a 100% turnover rate.',
    "Default administrative passwords for many IoT devices are still set to admin or 12345.",
    'My first pet was a goldfish named "Toaster" because he liked to jump toward the light.',
    "A restaurant where the menu is priced based on how much the ingredients cost at the stock market that morning.",
    "Zyzzy-vax the wonky-tonk in a purple skedaddle.",
    '"Save the Planet" campaigns are actually "Save the Humans" campaigns; the planet will be fine without us.',
    "I once spent three hours trying to find my glasses while I was wearing them.",
    "A mirror that shows you what you looked like exactly ten years ago today.",
]

INSERT_IDEA = """
INSERT INTO public.raw_idea (content, raw)
VALUES (%s, TRUE)
RETURNING id;
"""


def run():
    conn = psycopg2.connect(
        user=USER,
        password=PASSWORD,
        host=HOST,
        port=PORT,
        dbname=DBNAME,
    )
    try:
        with conn:
            with conn.cursor() as cur:
                # 1. Create tables
                print("Creating tables …")
                cur.execute(DDL)
                print("  ✓ Tables ready.")

                # 2. Insert seed ideas
                print("Inserting seed ideas …")
                inserted_ids = []
                for idea_text in SEED_IDEAS:
                    cur.execute(INSERT_IDEA, (idea_text,))
                    row = cur.fetchone()
                    inserted_ids.append(row[0])

                print(f"  ✓ Inserted {len(inserted_ids)} ideas (ids: {inserted_ids}).")

        print("\nSeed complete.")
    finally:
        conn.close()


if __name__ == "__main__":
    run()
