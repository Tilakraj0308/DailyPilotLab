"""
Seed script for DailyPilotLab.

- Creates the `raw_idea`, `topic`, `idea_topics`, and `trait` tables (with the
  pgvector extension enabled) in a Supabase Postgres instance whose credentials
  are read from the .env file (same keys as .env.example).
- Creates the `trait_category` enum type and associated triggers/functions.
- Inserts a set of sample ideas so the app has something to work with from day one.

Usage:
    python -m db.seed
"""

import psycopg2
from dotenv import load_dotenv
import os

load_dotenv()

USER = os.getenv("user")
PASSWORD = os.getenv("password")
HOST = os.getenv("host")
PORT = os.getenv("port")
DBNAME = os.getenv("dbname")

# ---------------------------------------------------------------------------
# DDL – types, tables, indexes, triggers, functions (all idempotent)
# ---------------------------------------------------------------------------

DDL = """
-- Enable the pgvector extension if it hasn't been enabled yet
CREATE EXTENSION IF NOT EXISTS vector SCHEMA extensions;

-- -------------------------------------------------------------------------
-- Enum: trait_category
-- -------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'trait_category') THEN
        CREATE TYPE public.trait_category AS ENUM (
            'interest',
            'goal',
            'skill',
            'routine',
            'workstyle',
            'preference',
            'avoidance',
            'value',
            'constraint'
        );
    END IF;
END
$$;

-- -------------------------------------------------------------------------
-- raw_idea
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.raw_idea (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    content     TEXT NULL DEFAULT '',
    embeddings  extensions.vector(1536) NULL,
    raw         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT rawIdea_pkey PRIMARY KEY (id)
);

-- -------------------------------------------------------------------------
-- topic
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.topic (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at          TIMESTAMP WITHOUT TIME ZONE NULL DEFAULT now(),
    title               TEXT NOT NULL,
    summary             TEXT NOT NULL,
    summary_embedding   extensions.vector(1536) NULL,
    activity_7d         SMALLINT NOT NULL DEFAULT 0,
    activity_30d        SMALLINT NOT NULL DEFAULT 0,
    lifetime_size       INTEGER NOT NULL DEFAULT 0,
    last_activity_at    TIME WITHOUT TIME ZONE NULL DEFAULT now(),
    is_archived         BOOLEAN NOT NULL DEFAULT FALSE,
    recency_strength    REAL NOT NULL DEFAULT 0,
    dominance           REAL NOT NULL DEFAULT 0,
    CONSTRAINT topic_pkey PRIMARY KEY (id)
);

-- Trigger: keep updated_at current on every UPDATE
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'update_topic_updated_at'
          AND tgrelid = 'public.topic'::regclass
    ) THEN
        CREATE TRIGGER update_topic_updated_at
        BEFORE UPDATE ON public.topic
        FOR EACH ROW
        EXECUTE FUNCTION storage.update_updated_at_column();
    END IF;
END
$$;

-- -------------------------------------------------------------------------
-- idea_topics (junction)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.idea_topics (
    idea_id     BIGINT NOT NULL,
    topic_id    BIGINT NOT NULL,
    CONSTRAINT idea_topics_pkey PRIMARY KEY (idea_id, topic_id),
    CONSTRAINT idea_topics_idea_id_fkey
        FOREIGN KEY (idea_id) REFERENCES public.raw_idea (id) ON DELETE CASCADE,
    CONSTRAINT idea_topics_topic_id_fkey
        FOREIGN KEY (topic_id) REFERENCES public.topic (id) ON DELETE CASCADE
);

-- -------------------------------------------------------------------------
-- trait
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.trait (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP WITH TIME ZONE NULL DEFAULT now(),
    trait_text  TEXT NOT NULL,
    trait_type  public.trait_category NOT NULL,
    confidence  REAL NOT NULL DEFAULT 0.1,
    embedding   extensions.vector(1536) NULL,
    CONSTRAINT trait_pkey PRIMARY KEY (id),
    CONSTRAINT trait_confidence_check CHECK (
        confidence >= 0.0 AND confidence <= 1.0
    )
);

-- HNSW index on trait embeddings for fast cosine-similarity lookups
CREATE INDEX IF NOT EXISTS idx_trait_embedding
    ON public.trait USING hnsw (embedding extensions.vector_cosine_ops);

-- Trigger: keep updated_at current on every UPDATE
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'update_trait_updated_at'
          AND tgrelid = 'public.trait'::regclass
    ) THEN
        CREATE TRIGGER update_trait_updated_at
        BEFORE UPDATE ON public.trait
        FOR EACH ROW
        EXECUTE FUNCTION storage.update_updated_at_column();
    END IF;
END
$$;

-- =========================================================================
-- Stored functions
-- =========================================================================

-- -------------------------------------------------------------------------
-- assign_and_return_matches(dist_threshold FLOAT)
--
-- Links every raw_idea that has no topic yet to any topic whose
-- summary_embedding is within dist_threshold (cosine distance).
-- Returns the newly linked ideas with their matched topics as JSON.
-- -------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.assign_and_return_matches(dist_threshold FLOAT)
RETURNS TABLE (
    idea_id     BIGINT,
    content     TEXT,
    topics      JSONB
)
LANGUAGE plpgsql AS
$$
BEGIN
    RETURN QUERY
    WITH new_links AS (
        INSERT INTO public.idea_topics AS new_it (idea_id, topic_id)
        SELECT i.id, t.id
        FROM public.raw_idea i
        CROSS JOIN public.topic t
        WHERE NOT EXISTS (
            SELECT 1
            FROM public.idea_topics existing_it
            WHERE existing_it.idea_id = i.id
        )
          AND (i.embeddings <=> t.summary_embedding) < dist_threshold
        RETURNING new_it.idea_id, new_it.topic_id
    )
    SELECT
        i.id,
        i.content,
        jsonb_agg(
            jsonb_build_object(
                'id',         t.id,
                'title',      t.title,
                'similarity', (1 - (i.embeddings <=> t.summary_embedding))
            )
        )
    FROM new_links nl
    JOIN public.raw_idea i ON nl.idea_id = i.id
    JOIN public.topic    t ON nl.topic_id = t.id
    GROUP BY i.id, i.content;
END;
$$;

-- -------------------------------------------------------------------------
-- update_topic_recency_metrics()
--
-- Recomputes lifetime_size, activity_7d, activity_30d, recency_strength,
-- and dominance for every topic based on its linked raw_ideas.
-- -------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.update_topic_recency_metrics()
RETURNS VOID
LANGUAGE plpgsql AS
$$
BEGIN
    WITH topic_metrics AS (
        SELECT
            t.id AS topic_id,
            COUNT(ri.id) AS lifetime_size,
            COUNT(ri.id) FILTER (WHERE ri.created_at >= NOW() - INTERVAL '7 days')  AS activity_7d,
            COUNT(ri.id) FILTER (WHERE ri.created_at >= NOW() - INTERVAL '30 days') AS activity_30d
        FROM public.topic t
        LEFT JOIN public.idea_topics it ON t.id = it.topic_id
        LEFT JOIN public.raw_idea    ri ON it.idea_id = ri.id
        GROUP BY t.id
    )
    UPDATE public.topic t
    SET
        lifetime_size    = tm.lifetime_size,
        activity_7d      = COALESCE(tm.activity_7d,   0),
        activity_30d     = COALESCE(tm.activity_30d,  0),
        -- Double weight for the last 7 days; single weight for rest of the month
        recency_strength = (COALESCE(tm.activity_7d, 0) * 2.0)
                         + ((COALESCE(tm.activity_30d, 0) - COALESCE(tm.activity_7d, 0)) * 1.0),
        -- 30% historical gravity + 70% current active weight
        dominance        = (tm.lifetime_size * 0.3)
                         + (COALESCE(tm.activity_30d, 0) * 0.7)
    FROM topic_metrics tm
    WHERE t.id = tm.topic_id;
END;
$$;
"""

# ---------------------------------------------------------------------------
# Seed data – ideas taken directly from ideas_inject.json
# ---------------------------------------------------------------------------

SEED_IDEAS = [
    "We don't actually see objects; we just see the light that failed to pass through them.",
    "Flibber-gasket the mimsy-wobble before the glorp transcends.",
    'The "oldest person on Earth" is a title that has a 100% turnover rate.',
    "Default administrative passwords for many IoT devices are still set to admin or 12345.",
    'My first pet was a goldfish named "Toaster" because he liked to jump toward the light.',
    "A restaurant where the menu is priced based on how much the ingredients cost at the stock market that morning.",
    "Zyzzy-vax the wonky-tonk in a purple skedaddle.",
    '"Save the Planet" campaigns are actually "Save the Humans" campaigns; the planet will be fine without us.',
    "I once spent three hours trying to find my glasses while I was wearing them.",
    "A mirror that shows you what you looked like exactly ten years ago today.",
]

INSERT_IDEA = """
INSERT INTO public.raw_idea (content, raw)
VALUES (%s, TRUE)
RETURNING id;
"""


def run():
    conn = psycopg2.connect(
        user=USER,
        password=PASSWORD,
        host=HOST,
        port=PORT,
        dbname=DBNAME,
    )
    try:
        with conn:
            with conn.cursor() as cur:
                # 1. Create types, tables, indexes, triggers, and functions
                print("Applying DDL …")
                cur.execute(DDL)
                print("  ✓ Schema ready.")

                # 2. Insert seed ideas
                print("Inserting seed ideas …")
                inserted_ids = []
                for idea_text in SEED_IDEAS:
                    cur.execute(INSERT_IDEA, (idea_text,))
                    row = cur.fetchone()
                    inserted_ids.append(row[0])

                print(f"  ✓ Inserted {len(inserted_ids)} ideas (ids: {inserted_ids}).")

        print("\nSeed complete.")
    finally:
        conn.close()


if __name__ == "__main__":
    run()
